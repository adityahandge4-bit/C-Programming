#include <stdio.h>

int main()
{
    int a = 90;     // Declare an integer variable 'a'
    float b = 8.76; // Declare a float variable 'b'
    printf("The value of a is %d\n the value of variable b is %f\n", a, b);
    int i = 10; // Declare 'i' and initialize with 10
    int j = i;
    printf("The value of i is %d\n the value of variable j is %d\n", i, j);
    // 02 Arithmetic Instructions
    // Declare 'j' and initialize with 'i'
    int e = 2, f = 3, c = 4, d = 5; // Declare and initialize multiple variables
    printf("The value of e is %d\n and the value of variable f is %d\n", e, f);
    printf("The value of c is %d\n and the value of variable d is %d", c, d);

    return 0;
}
// Above mentioned all the variables and their types of declaration is "Type declaration instruction"