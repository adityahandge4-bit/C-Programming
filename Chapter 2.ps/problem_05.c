/*
3.0 + 1 will be:
a. Integer.
b. Floating point number.
c. Character.
*/
// remember that whenever the operation of the float with integer is performed then the obtained result will be a floating point number
#include <stdio.h>

int main()
{
    float a = 3.0;
    int b = 1;
    printf("The result of a+b is %f", a + b);
    return 0;
}